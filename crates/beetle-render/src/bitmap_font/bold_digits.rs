/// Returns 8x12 bold digit glyph index if character is supported.
#[inline(always)]
pub fn get_bold_digit(c: char) -> Option<&'static [u8; 12]> {
    let idx = match c {
        '0'..='9' => c as usize - '0' as usize,
        '+' => 10,
        '-' => 11,
        '.' => 12,
        ':' => 13,
        '%' => 14,
        '/' => 15,
        _ => return None,
    };
    Some(&BOLD_DIGITS_8X12[idx])
}
