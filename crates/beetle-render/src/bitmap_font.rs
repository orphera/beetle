/// Embedded 5x7 ASCII bitmap font renderer.
pub struct BitmapFont;

impl BitmapFont {
    pub const GLYPH_WIDTH: u32 = 5;
    pub const GLYPH_HEIGHT: u32 = 7;
    pub const CHAR_SPACING: u32 = 1;

    /// Renders a single character glyph.
    pub fn draw_char(
        pixmap: &mut PixmapMut,
        c: char,
        x: i32,
        y: i32,
        scale: u32,
        color: ColorRgba,
    ) {
        let code = c as usize;
        if code < 32 || code > 126 {
            return;
        }

        let glyph = &FONT_5X7[code - 32];
        let skia_color = Color::from_rgba8(color.r, color.g, color.b, color.a);
        let scale = scale.max(1);

        for col in 0..5 {
            let col_bits = glyph[col];
            for row in 0..7 {
                if (col_bits & (1 << row)) != 0 {
                    let px = x + (col as i32 * scale as i32);
                    let py = y + (row as i32 * scale as i32);

                    if scale == 1 {
                        if px >= 0 && py >= 0 && (px as u32) < pixmap.width() && (py as u32) < pixmap.height() {
                            pixmap.fill_rect(
                                tiny_skia::Rect::from_xywh(px as f32, py as f32, 1.0, 1.0).unwrap(),
                                &tiny_skia::Paint {
                                    shader: tiny_skia::Shader::SolidColor(skia_color),
                                    ..Default::default()
                                },
                                tiny_skia::Transform::identity(),
                                None,
                            );
                        }
                    } else {
                        let rect_opt = tiny_skia::Rect::from_xywh(
                            px as f32,
                            py as f32,
                            scale as f32,
                            scale as f32,
                        );
                        if let Some(rect) = rect_opt {
                            pixmap.fill_rect(
                                rect,
                                &tiny_skia::Paint {
                                    shader: tiny_skia::Shader::SolidColor(skia_color),
                                    ..Default::default()
                                },
                                tiny_skia::Transform::identity(),
                                None,
                            );
                        }
                    }
                }
            }
        }
    }

    /// Renders a text string at (x, y) with scaling and color.
    pub fn draw_text(
        pixmap: &mut PixmapMut,
        text: &str,
        mut x: i32,
        y: i32,
        scale: u32,
        color: ColorRgba,
    ) {
        let scale = scale.max(1);
        let char_step = (Self::GLYPH_WIDTH + Self::CHAR_SPACING) as i32 * scale as i32;

        for c in text.chars() {
            Self::draw_char(pixmap, c, x, y, scale, color);
            x += char_step;
        }
    }

    /// Calculates horizontal width in pixels of a text string at a given scale.
    pub fn text_width(text: &str, scale: u32) -> u32 {
        let count = text.chars().count() as u32;
        if count == 0 {
            0
        } else {
            let scale = scale.max(1);
            let char_width = Self::GLYPH_WIDTH * scale;
            let spacing = Self::CHAR_SPACING * scale;
            count * char_width + (count - 1) * spacing
        }
    }

    /// Renders horizontally centered text.
    pub fn draw_text_centered(
        pixmap: &mut PixmapMut,
        text: &str,
        center_x: i32,
        y: i32,
        scale: u32,
        color: ColorRgba,
    ) {
        let width = Self::text_width(text, scale) as i32;
        let x = center_x - (width / 2);
        Self::draw_text(pixmap, text, x, y, scale, color);
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use tiny_skia::Pixmap;

    #[test]
    fn test_text_width() {
        // "1234" -> 4 chars. 4 * 5 + 3 * 1 = 23 at scale 1
        assert_eq!(BitmapFont::text_width("1234", 1), 23);
        assert_eq!(BitmapFont::text_width("1234", 2), 46);
        assert_eq!(BitmapFont::text_width("", 1), 0);
    }

    #[test]
    fn test_draw_text_pixmap() {
        let mut pixmap = Pixmap::new(100, 50).unwrap();
        pixmap.fill(Color::BLACK);

        let white = ColorRgba::new(255, 255, 255, 255);
        BitmapFont::draw_text(&mut pixmap.as_mut(), "HELLO 123", 10, 10, 2, white);

        // Verify that some pixels are drawn white
        let has_white_pixel = pixmap.data().chunks_exact(4).any(|p| p[0] == 255 && p[1] == 255 && p[2] == 255);
        assert!(has_white_pixel);
    }
}
